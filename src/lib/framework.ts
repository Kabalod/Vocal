export const DEFAULT_CRITERIA: CriterionDto[] = ANALYSIS_FRAMEWORK.categories.flatMap(
  (category, categoryIndex) =>
    category.criteria.map((criterion, criterionIndex) => ({
      id: criterion.id,
      label: criterion.name,
      description: criterion.question,
      weight: criterion.weight,
      enabled: true,
      sortOrder: categoryIndex * 20 + criterionIndex + 1,
      isExtended: false,
      categoryId: category.id,
      categoryLabel: category.name,
      categoryWeight: category.weight,
      categoryOrder: categoryIndex + 1,
    })),
);

export function sliceFramework(enabledIds: Set<string>) {
  return {
    name: ANALYSIS_FRAMEWORK.name,
    version: ANALYSIS_FRAMEWORK.version,
    categories: ANALYSIS_FRAMEWORK.categories
      .map((category) => ({
        ...category,
        criteria: category.criteria.filter((c) => enabledIds.has(c.id)),
      }))
      .filter((category) => category.criteria.length > 0),
  };
}

